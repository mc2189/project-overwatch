def normalise_evidence_type(value: str | None) -> str | None:
    if value is None:
        return None
    cleaned = str(value).strip().lower().replace("-", "_").replace(" ", "_")
    aliases = {
        "direct": EVIDENCE_DIRECT_OBSERVATION,
        "direct_lookup": EVIDENCE_THIRD_PARTY_SOURCE,
        "third_party": EVIDENCE_THIRD_PARTY_SOURCE,
        "inferred": EVIDENCE_PARSER_INFERRED,
        "parser": EVIDENCE_PARSER_INFERRED,
        "analyst": EVIDENCE_ANALYST_NOTE,
        "user": EVIDENCE_USER_SUPPLIED,
        "unavailable": EVIDENCE_UNAVAILABLE_SOURCE,
        "system": EVIDENCE_SYSTEM_GENERATED,
    }
    if cleaned in EVIDENCE_TYPES:
        return cleaned
    return aliases.get(cleaned)


def normalise_reliability(value: str | None) -> str | None:
    if value is None:
        return None
    cleaned = str(value).strip().lower()
    if cleaned in RELIABILITY_LEVELS:
        return cleaned
    return None


def default_evidence_for_module(module_id: str) -> dict[str, Any]:
    """Return sensible evidence defaults for a collection module."""
    defaults = MODULE_EVIDENCE_DEFAULTS.get(module_id, {}).copy()
    if not defaults:
        defaults = {
            "evidence_type": EVIDENCE_SYSTEM_GENERATED,
            "source_name": module_id,
            "source_url": None,
            "reliability": RELIABILITY_UNKNOWN,
            "collection_method": "module_run",
        }
    defaults.setdefault("module_version", PROJECT_VERSION)
    defaults.setdefault("collected_at", datetime.now(timezone.utc).isoformat())
    defaults["evidence_type"] = normalise_evidence_type(defaults.get("evidence_type"))
    defaults["reliability"] = normalise_reliability(defaults.get("reliability"))
    return defaults


def default_relationship_evidence(module_id: str, relationship_type: str) -> dict[str, Any]:
    """Return evidence metadata for a relationship created by a module."""
    key = (module_id, relationship_type)
    defaults = RELATIONSHIP_EVIDENCE_DEFAULTS.get(key)
    if defaults:
        return {
            "evidence_type": normalise_evidence_type(defaults["evidence_type"]),
            "reliability": normalise_reliability(defaults["reliability"]),
        }
    module_defaults = default_evidence_for_module(module_id)
    return {
        "evidence_type": EVIDENCE_PARSER_INFERRED,
        "reliability": module_defaults.get("reliability") or RELIABILITY_MEDIUM,
    }


def observation_evidence_for_module(
    module_id: str,
    result: dict[str, Any] | None = None,
) -> dict[str, Any]:
    """Return observation evidence metadata, adjusting for module-specific outcomes."""
    meta = default_evidence_for_module(module_id)
    if module_id == "infra_website_metadata" and result is not None:
        parsed = result.get("parsed_data") or {}
        homepage = parsed.get("homepage") or {}
        status = result.get("status", "")
        reachable = homepage.get("reachable")
        if status in {"partial", "error"} or reachable is False:
            meta["reliability"] = RELIABILITY_UNKNOWN
            if not homepage:
                meta["reliability"] = RELIABILITY_LOW
        elif reachable:
            meta["reliability"] = RELIABILITY_HIGH
    if module_id == "infra_email_security" and result is not None:
        status = result.get("status", "")
        if status in {"partial", "error"}:
            meta["reliability"] = RELIABILITY_MEDIUM
    if module_id == "infra_tls_review" and result is not None:
        parsed = result.get("parsed_data") or {}
        conn = parsed.get("connection") or {}
        if not conn.get("success"):
            meta["reliability"] = RELIABILITY_MEDIUM
            if conn.get("error"):
                meta["evidence_type"] = EVIDENCE_UNAVAILABLE_SOURCE
    if module_id == "infra_http_security" and result is not None:
        parsed = result.get("parsed_data") or {}
        response = parsed.get("response") or {}
        if not response.get("success"):
            meta["reliability"] = RELIABILITY_MEDIUM
            if response.get("error"):
                meta["evidence_type"] = EVIDENCE_UNAVAILABLE_SOURCE
    if module_id == "infra_web_stack_identifier" and result is not None:
        parsed = result.get("parsed_data") or {}
        response = parsed.get("response") or {}
        if not response.get("success"):
            meta["reliability"] = RELIABILITY_MEDIUM
            if response.get("error"):
                meta["evidence_type"] = EVIDENCE_UNAVAILABLE_SOURCE
    if module_id == "infra_web_path_review" and result is not None:
        parsed = result.get("parsed_data") or {}
        if not parsed.get("reachable"):
            meta["reliability"] = RELIABILITY_MEDIUM
            if parsed.get("path_results"):
                meta["reliability"] = RELIABILITY_MEDIUM
            else:
                meta["evidence_type"] = EVIDENCE_UNAVAILABLE_SOURCE
    if module_id == "infra_domain_intel" and result is not None:
        parsed = result.get("parsed_data") or {}
        http = parsed.get("http") or {}
        tls = parsed.get("tls") or {}
        dns = parsed.get("dns") or {}
        wayback = parsed.get("wayback") or {}
        if http or tls:
            meta["evidence_type"] = EVIDENCE_DIRECT_OBSERVATION
            meta["source_name"] = "http_response"
            meta["reliability"] = RELIABILITY_HIGH
            meta["collection_method"] = "mixed_passive_lookup"
        elif dns and not http and not tls:
            meta["evidence_type"] = EVIDENCE_THIRD_PARTY_SOURCE
            meta["source_name"] = "dns_lookup"
            meta["reliability"] = RELIABILITY_HIGH
        if wayback.get("error"):
            meta["collection_method"] = "mixed_passive_lookup"
    if module_id == "infra_cert_subdomain":
        meta["source_name"] = "crt.sh"
        meta["source_url"] = "https://crt.sh/"
    if module_id == "intel_virustotal" and result is not None:
        parsed = result.get("parsed_data") or {}
        if parsed.get("api", {}).get("error"):
            meta["reliability"] = RELIABILITY_UNKNOWN
            meta["evidence_type"] = EVIDENCE_UNAVAILABLE_SOURCE
    if module_id == "intel_abuseipdb" and result is not None:
        parsed = result.get("parsed_data") or {}
        if parsed.get("private_local_ip"):
            meta["evidence_type"] = EVIDENCE_SYSTEM_GENERATED
            meta["source_name"] = "project_overwatch"
            meta["reliability"] = RELIABILITY_HIGH
            meta["collection_method"] = "policy_skip"
        elif parsed.get("api", {}).get("error"):
            meta["reliability"] = RELIABILITY_UNKNOWN
            meta["evidence_type"] = EVIDENCE_UNAVAILABLE_SOURCE
    if module_id == "intel_greynoise" and result is not None:
        parsed = result.get("parsed_data") or {}
        if parsed.get("private_local_ip"):
            meta["evidence_type"] = EVIDENCE_SYSTEM_GENERATED
            meta["source_name"] = "project_overwatch"
            meta["reliability"] = RELIABILITY_HIGH
            meta["collection_method"] = "policy_skip"
        elif parsed.get("api", {}).get("error") and not parsed.get("api", {}).get("authenticated"):
            meta["reliability"] = RELIABILITY_UNKNOWN
            meta["evidence_type"] = EVIDENCE_UNAVAILABLE_SOURCE
    if module_id == "intel_shodan" and result is not None:
        parsed = result.get("parsed_data") or {}
        if parsed.get("private_local_ip"):
            meta["evidence_type"] = EVIDENCE_SYSTEM_GENERATED
            meta["source_name"] = "project_overwatch"
            meta["reliability"] = RELIABILITY_HIGH
            meta["collection_method"] = "policy_skip"
        elif parsed.get("api", {}).get("error"):
            meta["reliability"] = RELIABILITY_UNKNOWN
            meta["evidence_type"] = EVIDENCE_UNAVAILABLE_SOURCE
    if module_id == "intel_urlhaus" and result is not None:
        parsed = result.get("parsed_data") or {}
        if parsed.get("private_local_ip"):
            meta["evidence_type"] = EVIDENCE_SYSTEM_GENERATED
            meta["source_name"] = "project_overwatch"
            meta["reliability"] = RELIABILITY_HIGH
            meta["collection_method"] = "policy_skip"
        elif parsed.get("api", {}).get("error"):
            meta["reliability"] = RELIABILITY_UNKNOWN
            meta["evidence_type"] = EVIDENCE_UNAVAILABLE_SOURCE
    if module_id == "infra_whois_rdap" and result is not None:
        parsed = result.get("parsed_data") or result.get("data") or {}
        if parsed.get("private_local_ip"):
            meta["evidence_type"] = EVIDENCE_SYSTEM_GENERATED
            meta["source_name"] = "project_overwatch"
            meta["reliability"] = RELIABILITY_HIGH
            meta["collection_method"] = "local_classification"
        elif parsed.get("source") == "whois":
            meta["collection_method"] = "whois_fallback"
            meta["source_name"] = (parsed.get("whois_fallback") or {}).get("whois_server") or "whois"
        elif parsed.get("lookup_status") == "unavailable":
            meta["evidence_type"] = EVIDENCE_UNAVAILABLE_SOURCE
            meta["reliability"] = RELIABILITY_UNKNOWN
    return meta


def default_finding_evidence(
    module_id: str,
    finding: dict[str, Any] | None = None,
) -> dict[str, Any]:
    """Derive finding evidence fields from module defaults and finding context."""
    from utils.finding_interpreter import is_source_notice

    if finding and is_source_notice(finding):
        module_defaults = default_evidence_for_module(module_id)
        return {
            "evidence_type": EVIDENCE_UNAVAILABLE_SOURCE,
            "source_name": module_defaults.get("source_name") or module_id,
            "reliability": RELIABILITY_LOW,
        }

    if finding:
        evidence_type = normalise_evidence_type(finding.get("evidence_type"))
        reliability = normalise_reliability(finding.get("reliability"))
        source_name = finding.get("source_name")
        if evidence_type or reliability or source_name:
            module_defaults = default_evidence_for_module(module_id)
            return {
                "evidence_type": evidence_type or module_defaults.get("evidence_type"),
                "source_name": source_name or module_defaults.get("source_name"),
                "reliability": reliability or module_defaults.get("reliability"),
            }

    module_defaults = default_evidence_for_module(module_id)
    return {
        "evidence_type": module_defaults.get("evidence_type"),
        "source_name": module_defaults.get("source_name"),
        "reliability": module_defaults.get("reliability"),
    }


def attach_evidence_metadata(
    record_data: dict[str, Any],
    module_id: str,
    source_name: str | None = None,
    source_url: str | None = None,
) -> dict[str, Any]:
    """Merge module evidence defaults into a record payload."""
    merged = {**default_evidence_for_module(module_id), **record_data}
    if source_name:
        merged["source_name"] = source_name
    if source_url:
        merged["source_url"] = source_url
    merged["evidence_type"] = normalise_evidence_type(merged.get("evidence_type"))
    merged["reliability"] = normalise_reliability(merged.get("reliability"))
    return merged


def evidence_type_label(evidence_type: str | None) -> str:
    if not evidence_type:
        return "Unknown"
    return EVIDENCE_TYPE_LABELS.get(evidence_type, evidence_type.replace("_", " ").title())


def reliability_label(reliability: str | None) -> str:
    if not reliability:
        return "Unknown"
    return RELIABILITY_LABELS.get(reliability, reliability.title())


def evidence_wording(evidence_type: str | None) -> str:
    if not evidence_type:
        return "Evidence classification not recorded"
    return EVIDENCE_WORDING.get(evidence_type, evidence_type_label(evidence_type))
